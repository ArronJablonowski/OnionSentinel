PROXY_SOURCE_TEMPLATE = """// Generated by sync-pcap-broker-workflow.py. PCAP bytes never pass through n8n.
const http = require('http');
const {URLSearchParams} = require('url');
const expectedToken = $vars.PCAP_BROKER_TOKEN || 'REPLACE_WITH_PCAP_BROKER_TOKEN';
const headers = $json.headers || {};
const token = headers['x-relay-token'] || headers['X-Relay-Token'];
if (token !== expectedToken) {
  return [{json: {ok: false, status: 'rejected', reason: 'invalid or missing X-Relay-Token'}}];
}
const query = $json.query || {};
const body = $json.body || {};
const requestParams = %s;
const params = new URLSearchParams();
for (const [key, value] of Object.entries(requestParams)) {
  if (Array.isArray(value)) value.forEach(item => params.append(key, item));
  else if (value !== undefined && value !== null && value !== '') params.set(key, value);
}
const path = `%s` + (params.toString() ? `?${params.toString()}` : '');
function requestAlertStore() {
  return new Promise((resolve, reject) => {
    const data = `%s` === 'GET' ? null : JSON.stringify(body || {});
    const req = http.request({
      hostname: 'alert-store',
      port: 8787,
      path,
      method: `%s`,
      headers: data ? {'Content-Type': 'application/json', 'Content-Length': Buffer.byteLength(data)} : {},
      timeout: 20000,
    }, res => {
      let responseBody = '';
      res.setEncoding('utf8');
      res.on('data', chunk => responseBody += chunk);
      res.on('end', () => resolve({statusCode: res.statusCode, body: responseBody}));
    });
    req.on('timeout', () => req.destroy(new Error('alert-store pcap broker timed out')));
    req.on('error', reject);
    if (data) req.write(data);
    req.end();
  });
}
try {
  const response = await requestAlertStore();
  let payload;
  try { payload = JSON.parse(response.body || '{}'); }
  catch (error) { throw new Error(`alert-store returned non-JSON: ${response.body.slice(0, 200)}`); }
  return [{json: {...payload, proxy_status_code: response.statusCode}}];
} catch (error) {
  return [{json: {ok: false, status: 'error', reason: String(error.message || error).slice(0, 240)}}];
}
"""


def proxy_source(spec: dict[str, object]) -> str:
    method = str(spec["target_method"])
    target_path = str(spec["target_path"])
    request_params = "{...body, ...query}" if spec.get("forward_body_as_query") else "query"
    return PROXY_SOURCE_TEMPLATE % (
        request_params,
        target_path,
        method,
        method,
    )


def rendered_workflow(original: dict[str, object]) -> dict[str, object]:
    nodes: list[dict[str, object]] = []
    connections: dict[str, object] = {}
    for index, spec in enumerate(ENDPOINTS):
        y = index * 220
        webhook_name = str(spec["webhook_name"])
        code_name = str(spec["code_name"])
        nodes.extend(
            [
                {
                    "parameters": {
                        "httpMethod": "POST",
                        "path": spec["webhook_path"],
                        "responseMode": "lastNode",
                        "options": {},
                    },
                    "id": spec["webhook_node_id"],
                    "name": webhook_name,
                    "type": "n8n-nodes-base.webhook",
                    "typeVersion": 2,
                    "position": [0, y],
                    "webhookId": spec["webhook_id"],
                },
                {
                    "parameters": {"jsCode": proxy_source(spec)},
                    "id": spec["code_node_id"],
                    "name": code_name,
                    "type": "n8n-nodes-base.code",
                    "typeVersion": 2,
                    "position": [260, y],
                },
            ]
        )
        connections[webhook_name] = {
            "main": [[{"node": code_name, "type": "main", "index": 0}]]
        }
    rendered = dict(original)
    rendered["nodes"] = nodes
    rendered["connections"] = connections
    return rendered


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    current = json.loads(WORKFLOW.read_text(encoding="utf-8"))
    expected = json.dumps(rendered_workflow(current), indent=2, ensure_ascii=True) + "\n"
    actual = WORKFLOW.read_text(encoding="utf-8")
    if args.check:
        if actual != expected:
            raise SystemExit("PCAP broker workflow is out of sync; run sync-pcap-broker-workflow.py")
        return 0
    WORKFLOW.write_text(expected, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
